def render_overview():

    render_header(
        "Supply Chain Overview",
        "Monitor shipments, inventory, suppliers and operational disruptions.",
    )

    data = get_active_data()

    shipments_df = data["shipments"]
    inventory_df = data["inventory"]
    suppliers_df = data["suppliers"]

    total_shipments = len(shipments_df)

    delayed = (
        shipments_df["status"].astype(str).str.lower().eq("delayed").sum()
        if "status" in shipments_df.columns else 0
    )

    at_risk = (
        shipments_df["status"].astype(str).str.lower().eq("at risk").sum()
        if "status" in shipments_df.columns else 0
    )

    critical_inventory = 0

    if {
        "available_stock",
        "reorder_level",
    }.issubset(inventory_df.columns):

        critical_inventory = (
            pd.to_numeric(
                inventory_df["available_stock"], errors="coerce"
            )
            <
            pd.to_numeric(
                inventory_df["reorder_level"], errors="coerce"
            )
        ).sum()

    # KPI CARDS

    col1, col2, col3, col4 = st.columns(4)

    col1.metric(
        "Total Shipments",
        total_shipments,
    )

    col2.metric(
        "Delayed Shipments",
        int(delayed),
        delta_color="inverse",
    )

    col3.metric(
        "At-Risk Shipments",
        int(at_risk),
        delta_color="inverse",
    )

    col4.metric(
        "Critical Inventory",
        int(critical_inventory),
        delta_color="inverse",
    )

    st.markdown("---")

    # CHARTS

    left, right = st.columns(2)

    with left:

        st.markdown("### Shipment Status")

        if "status" in shipments_df.columns:

            status_data = (
                shipments_df["status"]
                .value_counts()
                .reset_index()
            )

            status_data.columns = ["Status", "Count"]

            fig = px.pie(
                status_data,
                names="Status",
                values="Count",
                hole=0.62,
                title="Shipment Distribution",
            )

            st.plotly_chart(
                style_chart(fig),
                use_container_width=True,
            )

        else:
            st.info("No shipment status column found.")

    with right:

        st.markdown("### Inventory Availability")

        if {
            "product_name",
            "available_stock",
        }.issubset(inventory_df.columns):

            fig = px.bar(
                inventory_df,
                x="product_name",
                y="available_stock",
                title="Available Stock by Product",
            )

            fig.update_layout(
                xaxis_title="Product",
                yaxis_title="Available Units",
            )

            st.plotly_chart(
                style_chart(fig),
                use_container_width=True,
            )

        else:
            st.info("Inventory chart data is unavailable.")

    # OPERATIONAL ALERTS

    st.markdown("### 🚨 Operational Alerts")

    if "status" in shipments_df.columns:

        delayed_shipments = shipments_df[
            shipments_df["status"].astype(str).str.lower() == "delayed"
        ]

        if delayed_shipments.empty:
            st.success("No delayed shipments in the current dataset.")

        else:
            for _, row in delayed_shipments.iterrows():

                shipment_id = row.get("shipment_id", "Unknown")
                supplier_id = row.get("supplier_id", "Unknown")
                delay = row.get("delay_days", "Unknown")

                st.warning(
                    f"{shipment_id} | Supplier: {supplier_id} | "
                    f"Delay: {delay} days"
                )

    st.markdown("### Recent Shipment Activity")

    st.dataframe(
        shipments_df,
        use_container_width=True,
        hide_index=True,
    )

    st.caption("Data source: Synthetic demonstration records or uploaded CSVs.")


