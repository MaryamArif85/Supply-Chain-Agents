def render_supply_chain_data():

    render_header(
        "Supply Chain Data Explorer",
        "Explore demonstration datasets and upload your own operational CSV files.",
    )

    active_data = get_active_data()

    dataset_options = {
        "Shipments": active_data["shipments"],
        "Inventory": active_data["inventory"],
        "Suppliers": active_data["suppliers"],
    }

    st.markdown("### Dataset Overview")

    data_type = st.selectbox(
        "Select Dataset",
        list(dataset_options.keys()),
    )

    selected_data = dataset_options[data_type]

    st.dataframe(
        selected_data,
        use_container_width=True,
        hide_index=True,
    )

    source_label = (
        "Uploaded dataset"
        if data_type in st.session_state.uploaded_data
        else "Synthetic demonstration dataset"
    )

    st.caption(
        f"{len(selected_data)} records | "
        f"{len(selected_data.columns)} columns | "
        f"{source_label}"
    )

    st.divider()

    st.markdown("### Upload Your Own Dataset")

    upload_type = st.selectbox(
        "Choose Dataset Type",
        [
            "Shipments",
            "Inventory",
            "Suppliers",
        ],
        key="upload_type",
    )

    uploaded_file = st.file_uploader(
        "Upload CSV file",
        type=["csv"],
        key="dataset_uploader",
    )

    if uploaded_file:

        try:

            uploaded_df = pd.read_csv(uploaded_file)

            if uploaded_df.empty:
                st.warning("The uploaded CSV contains no records.")

            else:

                st.session_state.uploaded_data[upload_type] = uploaded_df

                st.success(
                    f"{upload_type} dataset uploaded successfully."
                )

                st.markdown("#### Dataset Preview")

                st.dataframe(
                    uploaded_df.head(10),
                    use_container_width=True,
                )

                st.write(
                    f"Rows: {uploaded_df.shape[0]} | "
                    f"Columns: {uploaded_df.shape[1]}"
                )

                st.info(
                    "This dataset will be used in future crisis investigations "
                    "instead of the corresponding demonstration dataset."
                )

        except Exception as error:

            st.error(f"Unable to read CSV file: {error}")

    if st.session_state.uploaded_data:

        st.divider()

        st.markdown("### Uploaded Datasets")

        for name, dataframe in st.session_state.uploaded_data.items():

            st.write(
                f"**{name}:** {len(dataframe)} rows, "
                f"{len(dataframe.columns)} columns"
            )

        if st.button("Clear Uploaded Datasets"):

            st.session_state.uploaded_data = {}
            st.rerun()


