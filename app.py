def render_crisis_simulation():

    render_header(
        "Crisis Simulation",
        "Create a supply-chain disruption and launch the AI investigation.",
    )

    st.markdown("### 🚨 Disruption Information")

    with st.form("crisis_form"):

        crisis_type = st.selectbox(
            "Select Crisis Type",
            [
                "Supplier Failure",
                "Shipment Delay",
                "Port Congestion",
                "Inventory Shortage",
                "Transportation Disruption",
                "Multiple Disruptions",
            ],
        )

        col1, col2 = st.columns(2)

        with col1:

            supplier_options = (
                suppliers["supplier_name"].astype(str).tolist()
                if "supplier_name" in suppliers.columns
                else ["Unknown Supplier"]
            )

            shipment_options = (
                shipments["shipment_id"].astype(str).tolist()
                if "shipment_id" in shipments.columns
                else ["Unknown Shipment"]
            )

            supplier = st.selectbox(
                "Affected Supplier",
                supplier_options,
            )

            shipment_id = st.selectbox(
                "Affected Shipment",
                shipment_options,
            )

        with col2:

            severity = st.select_slider(
                "Crisis Severity",
                options=[
                    "Low",
                    "Medium",
                    "High",
                    "Critical",
                ],
                value="High",
            )

            estimated_delay = st.number_input(
                "Estimated Delay (Days)",
                min_value=0,
                max_value=90,
                value=5,
            )

        description = st.text_area(
            "Additional Crisis Details",
            placeholder=(
                "Example: The supplier has reported a factory shutdown "
                "and cannot deliver raw materials on time..."
            ),
        )

        submitted = st.form_submit_button(
            "🚀 Initiate AI Crisis Investigation",
            use_container_width=True,
            type="primary",
        )

    # --------------------------------------------------------
    # EXECUTE CREW
    # --------------------------------------------------------

    if submitted:

        crisis_data = {
            "crisis_type": crisis_type,
            "supplier": supplier,
            "shipment_id": shipment_id,
            "severity": severity,
            "estimated_delay_days": estimated_delay,
            "description": description,
        }

        st.session_state.crisis_data = crisis_data
        st.session_state.simulation_started = True
        st.session_state.investigation_result = None
        st.session_state.task_outputs = []
        st.session_state.investigation_error = None

        active_data = get_active_data()

        try:

            with st.status(
                "🚀 SupplyChain Sentinel investigation running...",
                expanded=True,
            ) as status:

                st.write("🚨 Disruption Analyst: Investigating crisis...")
                st.write("📦 Inventory Analyst: Analyzing stock levels...")
                st.write("🏭 Supplier Intelligence: Evaluating suppliers...")
                st.write("🚚 Logistics Optimizer: Examining shipments...")
                st.write("🛡️ Risk Analyst: Assessing operational risks...")
                st.write("🧠 Recovery Coordinator: Preparing recovery plan...")

                result = run_crisis_investigation(
                    crisis_data=crisis_data,
                    supply_chain_data=active_data,
                )

                # Extract final CrewAI output
                final_output = getattr(result, "raw", None)

                if not final_output:
                    final_output = str(result)

                st.session_state.investigation_result = str(final_output)

                # Extract individual task outputs
                task_outputs = []

                for index, task_output in enumerate(
                    getattr(result, "tasks_output", []) or []
                ):

                    task_outputs.append({
                        "number": index + 1,
                        "agent": getattr(
                            task_output,
                            "agent",
                            f"Agent {index + 1}",
                        ),
                        "description": getattr(
                            task_output,
                            "description",
                            "",
                        ),
                        "output": getattr(
                            task_output,
                            "raw",
                            str(task_output),
                        ),
                    })

                st.session_state.task_outputs = task_outputs

                status.update(
                    label="✅ Investigation completed successfully!",
                    state="complete",
                    expanded=False,
                )

        except Exception as error:

            logger.exception("Crew execution failed.")

            st.session_state.investigation_error = str(error)

            st.error("The investigation could not be completed.")

            st.exception(error)

    # --------------------------------------------------------
    # DISPLAY CRISIS INFORMATION
    # --------------------------------------------------------

    if st.session_state.crisis_data:

        st.divider()

        st.markdown("### Registered Crisis")

        st.json(st.session_state.crisis_data)

    # --------------------------------------------------------
    # DISPLAY ERRORS
    # --------------------------------------------------------

    if st.session_state.investigation_error:

        st.error("The investigation encountered an error.")

        st.code(
            st.session_state.investigation_error,
            language="text",
        )

    # --------------------------------------------------------
    # DISPLAY FINAL AI REPORT
    # --------------------------------------------------------

    render_investigation_results()



