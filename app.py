def style_chart(fig):
    fig.update_layout(
        template="plotly_dark",
        paper_bgcolor="#111c2e",
        plot_bgcolor="#111c2e",
        font=dict(
            family="DM Sans",
            color="#edf3fa",
        ),
        margin=dict(l=20, r=20, t=40, b=20),
        legend=dict(
            bgcolor="rgba(0,0,0,0)",
        ),
    )

    return fig


