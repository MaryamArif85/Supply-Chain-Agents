def render_agent_execution():

    render_header(
        "Agent Execution Center",
        "Monitor the six AI specialists and inspect their investigation findings.",
    )

    st.markdown("### Multi-Agent Workforce")

    agents = config.AGENTS

    for i in range(0, len(agents), 2):

        col1, col2 = st.columns(2)

        for col, agent in zip(
            [col1, col2],
            agents[i:i + 2],
        ):

            with col:

                st.markdown(
                    f"""
                    <div class="agent-card">
                        <div style="font-size: 25px;">
                            {agent['icon']}
                        </div>
                        <div class="agent-name">
                            {agent['name']}
                        </div>
                        <div style="color:#36a3ff; font-size:12px;">
                            {agent['role']}
                        </div>
                        <div class="agent-description">
                            {agent['description']}
                        </div>
                    </div>
                    """,
                    unsafe_allow_html=True,
                )

    st.divider()

    st.markdown("### Agent Workflow")

    if st.session_state.task_outputs:

        for task in st.session_state.task_outputs:

            with st.expander(
                f"Step {task['number']} — {task['agent']}",
                expanded=False,
            ):

                if task["description"]:
                    st.caption(task["description"])

                st.markdown(task["output"])

        st.success("All six agent tasks have returned their results.")

    elif st.session_state.investigation_error:

        st.error("The last investigation did not complete successfully.")

    else:

        st.info(
            "No investigation has been executed yet. "
            "Go to Crisis Simulation to start the six-agent workflow."
        )

        for index, agent in enumerate(agents, start=1):

            st.markdown(
                f"**{index}. {agent['icon']} {agent['name']}**"
            )

            if index < len(agents):
                st.caption("↓")


